#!/usr/bin/env python3
r"""
report.py - assemble the master report INDEX from the machine-generated benchmark
outputs + the static review documents, injecting the latest measured numbers so the
top-level summary is never stale.

It does NOT invent numbers. If a benchmark hasn't been run, it says "not yet measured
(run on server)" rather than printing a fake accuracy. That honesty is the point.

USAGE
    python eval/report.py --reports eval/reports/ --out eval/reports/INDEX.md
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

STATIC_REPORTS = [
    ("00_EXECUTIVE_SUMMARY.md", "Production-readiness score + the ranked action plan"),
    ("01_ARCHITECTURE_REVIEW.md", "Data flow, module map, built-vs-claimed gaps"),
    ("02_CODE_REVIEW.md", "Every dimension scored 1-10 with file:line evidence"),
    ("03_ACCURACY_AND_RISK.md", "Per-type accuracy assessment + silent-data-loss risk register"),
    ("04_ACTION_PLAN.md", "Ranked High/Med/Low fixes with file:line, effort, invariant"),
    ("05_VERIFIED_NO_GPU_RUN.md", "What was actually EXECUTED (tests, digital runs) + confirmed bugs"),
    ("SERVER_RUNBOOK.md", "GPU/JVM benchmarks to run on the server"),
]
GENERATED = [
    ("benchmark_accuracy.md", "Measured table/text accuracy vs golden"),
    ("benchmark_speed.md", "Measured wall-time + peak RSS per file"),
    ("confidence.md", "HITL routing: what auto-accepts vs needs the original source"),
]


def _summarise_accuracy(reports: Path) -> str:
    p = reports / "benchmark_accuracy.json"
    if not p.exists():
        return "_Accuracy: not yet measured. Build goldens (eval/golden/README.md) then " \
               "`python eval/run_benchmark.py score --run out/ --golden eval/golden/`._"
    data = json.loads(p.read_text(encoding="utf-8"))
    lines = ["| type | files | content F1 | positional F1 | row acc | TEDS | misplace | CER |",
             "|---|---|---|---|---|---|---|---|"]
    for t, b in data.get("by_type", {}).items():
        lines.append(f"| {t} | {b['files']} | {b['mean_table_f1']} | {b.get('mean_positional_f1','-')} | "
                     f"{b.get('mean_row_accuracy','-')} | {b['mean_teds_lite']} | "
                     f"{b.get('mean_misplacement','-')} | {b.get('mean_cer')} |")
    return "\n".join(lines)


def _summarise_confidence(reports: Path) -> str:
    p = reports / "confidence.csv"
    if not p.exists():
        return "_HITL routing: not yet generated. `python eval/confidence_report.py --run out/`._"
    import csv
    counts: dict[str, int] = {}
    with p.open(encoding="utf-8") as fh:
        for row in csv.DictReader(fh):
            counts[row["verdict"]] = counts.get(row["verdict"], 0) + 1
    return " · ".join(f"**{k}**: {v}" for k, v in counts.items()) or "_no items_"


def main() -> None:
    ap = argparse.ArgumentParser(description="Assemble the master report index.")
    ap.add_argument("--reports", default="eval/reports")
    ap.add_argument("--out", default="eval/reports/INDEX.md")
    a = ap.parse_args()
    reports = Path(a.reports)
    reports.mkdir(parents=True, exist_ok=True)

    L = ["# kb-extract-rig — review & benchmark index", "",
         "Generated by `eval/report.py`. The static reviews are written by the "
         "`extract-rig-qa` agent; the measured numbers below come from the benchmark "
         "harness and are re-injected each time you regenerate this file.", "",
         "## Latest measured accuracy", "", _summarise_accuracy(reports), "",
         "## Latest HITL routing", "", _summarise_confidence(reports), "",
         "## Reports", ""]
    for name, desc in STATIC_REPORTS:
        mark = "" if (reports / name).exists() else "  _(missing)_"
        L.append(f"- [{name}]({name}) — {desc}{mark}")
    L.append("")
    L.append("### Machine-generated (re-run the harness to refresh)")
    for name, desc in GENERATED:
        mark = "" if (reports / name).exists() else "  _(not yet run)_"
        L.append(f"- [{name}]({name}) — {desc}{mark}")

    Path(a.out).write_text("\n".join(L), encoding="utf-8")
    print(f"[ok] {a.out}")


if __name__ == "__main__":
    main()
